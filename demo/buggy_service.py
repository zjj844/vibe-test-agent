"""示例被测服务（故意带 Bug）—— 用来演示"缺陷报告"怎么产生

=====================================================================
这是什么
=====================================================================
一个最小的订单查询服务，两个接口：

    GET /api/items            → 正常（返回商品列表）
    GET /api/orders/42        → **故意坏掉**（500）

=====================================================================
为什么仓库里要放一个"坏服务"
=====================================================================
因为「系统 Bug 不许改测试」是这个项目最重要的一条原则，
但只用单元测试验证它是不够的 —— 看报告的人会问"那真跑起来是什么样？"。

这个 fixture 就是用来回答这个问题的：一条命令就能复现一份真实的缺陷报告，
证明工具在遇到服务端 500 时**不会去改测试让它变绿**，只会停下来说明"这是服务的问题"。

=====================================================================
Bug 是怎么埋的（对照真实世界的 bug）
=====================================================================
`/api/orders/42` 里：查订单时没判断"查不到"的情况，直接对 None 取属性。
真实项目里这类 bug 极其常见 —— 某条数据缺失就抛 500，平时跑不到、上线才炸。

=====================================================================
怎么用
=====================================================================
    python demo/buggy_service.py            # 起在 127.0.0.1:8090
    python -m selfheal.loop --target demo-buggy --n 2 --rounds 2
    # → reports/REPORT-*.md 里会出现"缺陷清单"一节，结论是"发现服务端缺陷"

依赖：只有 Flask（和被测项目 rag-backend 用的是同一个）。
"""
from __future__ import annotations

from flask import Flask, jsonify

app = Flask(__name__)

# 商品数据（这部分是好的）
_ITEMS = [
    {"id": 1, "name": "机械键盘", "price": 399},
    {"id": 2, "name": "显示器", "price": 1299},
]

# 订单表：**故意没有 42 号订单**，用来触发"查不到就崩"的 bug
_ORDERS = {
    41: {"id": 41, "item_id": 1, "qty": 2, "status": "paid"},
}


@app.get("/api/items")
def list_items():
    """正常接口：返回商品列表。契约要求 data 是数组、code 是 200。"""
    return jsonify({"code": 200, "msg": "操作成功", "data": _ITEMS})


@app.get("/api/orders/<int:order_id>")
def order_detail(order_id: int):
    """**带 Bug 的接口**。

    `_ORDERS[order_id]` 在 order_id 不存在时抛 KeyError，Flask 兜底成 500。
    正确写法应该是：查不到就返回 404 + code=404（契约里也这么要求）。
    这就是典型的"服务端缺陷"——测试断言"应该 200/404"没有错，错的是服务。
    """
    order = _ORDERS[order_id]          # ← Bug 在这里：没有 get / 没有存在性判断
    return jsonify({"code": 200, "msg": "操作成功", "data": order})


if __name__ == "__main__":
    print("示例被测服务（故意带 Bug）已启动：http://127.0.0.1:8090")
    print("  正常接口：GET /api/items")
    print("  坏的接口：GET /api/orders/42  → 500")
    app.run(host="127.0.0.1", port=8090, debug=False)
